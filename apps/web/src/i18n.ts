export function translate(language: InterfaceLanguage, text: string): string {
  return language === "zh-CN" ? (chinese[text] ?? text) : text;
}

export function useInterfaceLanguage() {
  return useLocalStorage(LANGUAGE_KEY, "en" as InterfaceLanguage, Language);
}

export function readInterfaceLanguage(): InterfaceLanguage {
  return readLocalStorageValue(LANGUAGE_KEY, "en" as InterfaceLanguage, Language);
}

export function useTranslation() {
  const [language] = useInterfaceLanguage();
  return (text: string) => translate(language, text);
}
